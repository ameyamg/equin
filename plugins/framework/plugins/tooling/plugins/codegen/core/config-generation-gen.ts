import { joinAppPath } from "@plugins/infra/plugins/host-fs/plugins/user-path/core";
import { asFsPath } from "@plugins/framework/plugins/plugin-id/core";
import type { RepoSnapshot } from "@plugins/framework/plugins/tooling/core";
import {
  configGenerationId,
  MERGE_ENGINE,
  type ConfigPluginMove,
} from "@plugins/config_v2/core";
import {
  parsePluginMoves,
  PLUGIN_MOVES_FILE,
  pluginMoveKey,
} from "@plugins/plugin-meta/plugins/relocate/core";
import { configMigrationKeys } from "./config-origin-gen";
import { writeGenerated } from "./write-generated";
import type { CodegenPass } from "./codegen-pass";

/** Where the generation module is written — read by config_v2's machine half. */
export const CONFIG_GENERATION_REL_PATH =
  "plugins/config_v2/core/config-generation.generated.ts";

/**
 * The generated module naming this tree's config generation and carrying what
 * its derive needs and a backend cannot read from a checkout (a release has
 * none): the plugin-move ledger, each entry with its ledger key and whether
 * its old id is a plugin again.
 *
 * `CONFIG_GENERATION` is `configGenerationId` over the committed `config/`
 * files (path + git blob id — the repo's own file set and ids, so the build
 * and `config-origins-in-sync` read the very same inputs), the move ledger's
 * blob id, every config migration's key and the merge engine. The module is in
 * `config_v2#machine`'s code closure (a literal `import()`), so a change to
 * any input is a change to the backend's code: a deploy restarts it rather
 * than adopting it, and the new backend derives its generation at boot.
 */
export async function renderConfigGeneration(opts: {
  pass: CodegenPass;
  repo: RepoSnapshot;
}): Promise<string> {
  const { repo } = opts;
  const committed = repo
    .under("config")
    .filter((rel) => rel.endsWith(".jsonc"))
    .map((rel) => [rel, repo.blobOf(rel)] as const);
  const movesText = repo.has(PLUGIN_MOVES_FILE)
    ? await repo.read(PLUGIN_MOVES_FILE)
    : null;
  const id = configGenerationId({
    committed,
    pluginMoves: movesText === null ? "" : repo.blobOf(PLUGIN_MOVES_FILE),
    migrationKeys: await configMigrationKeys(opts.pass),
    mergeEngine: MERGE_ENGINE,
  });
  const moves: ConfigPluginMove[] =
    movesText === null
      ? []
      : parsePluginMoves(movesText).map((m) => ({
          key: pluginMoveKey(m),
          from: m.from,
          to: m.to,
          fromIsPlugin: repo.has(`plugins/${asFsPath(m.from)}/package.json`),
        }));
  return [
    "// DO NOT EDIT — autogenerated by `./equin build`",
    "// (see plugins/framework/plugins/tooling/plugins/codegen/core/config-generation-gen.ts).",
    "//",
    "// The config generation this tree's backend reads — a hash of the committed",
    "// config/ tree, the plugin-move ledger, every config migration and the merge",
    "// engine; its user layer is `<namespace>/gens/<id>/` — and the move ledger its",
    "// derive replays (config_v2#machine).",
    `export const CONFIG_GENERATION = ${JSON.stringify(id)};`,
    "",
    "export const CONFIG_PLUGIN_MOVES: readonly {",
    "  key: string;",
    "  from: string;",
    "  to: string;",
    "  fromIsPlugin: boolean;",
    `}[] = ${JSON.stringify(moves, null, 2)};`,
    "",
  ].join("\n");
}

/**
 * Write the config generation module from the checkout as it stands now (the
 * pass's set relisted) — run after every step that writes `config/` (origins,
 * legends, a move's re-stamp, the authored-override seeder).
 */
export async function generateConfigGeneration(opts: {
  pass: CodegenPass;
}): Promise<void> {
  await writeGenerated({
    file: joinAppPath(opts.pass.root, CONFIG_GENERATION_REL_PATH),
    content: await renderConfigGeneration({
      pass: opts.pass,
      repo: await opts.pass.phaseRepo(),
    }),
  });
}
